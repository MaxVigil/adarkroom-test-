  addToTooltip: function(tooltip, key) {
    if(!tooltip || tooltip.length === 0) return tooltip;

    $('.tooltipDescription', tooltip).remove();
    var description = EntityDescriptions.get(key);
    if(!description) return tooltip;

    tooltip.addClass('entityTooltip').attr('data-entity', key);
    $('<div>').addClass('tooltipDescription').text(description).prependTo(tooltip);
    return tooltip;
  },

  attach: function(element, key, position) {
    if(!element || element.length === 0 || !EntityDescriptions.get(key)) return element;

    element.addClass('hasEntityDescription').attr('data-entity', key);
    var tooltip = element.children('div.tooltip').first();
    if(tooltip.length === 0) {
      tooltip = $('<div>').addClass('tooltip ' + (position || 'bottom right')).appendTo(element);
    }
    EntityDescriptions.addToTooltip(tooltip, key);
    return element;
  },

  positionTooltip: function(element) {
    var sourceTooltip = element.children('div.entityTooltip').first();
    if(sourceTooltip.length === 0 || (!element.is(':hover') && !element.is(':focus'))) return;

    EntityDescriptions.cancelTooltipHide();
    $('body > div.entityTooltipFloating').remove();
    sourceTooltip.css('visibility', 'hidden');
    var tooltip = sourceTooltip.clone()
      .addClass('entityTooltipFloating')
      .appendTo('body')
      .on('mouseenter.entityDescriptions', EntityDescriptions.cancelTooltipHide)
      .on('mouseleave.entityDescriptions', function() {
        EntityDescriptions.scheduleTooltipHide(element);
      });

    var targetRect = element[0].getBoundingClientRect();
    var viewportPadding = 8;
    var maxHeight = Math.max(120, window.innerHeight - (viewportPadding * 2));

    tooltip.css({
      position: 'fixed',
      visibility: 'hidden',
      display: 'block',
      top: '0px',
      left: '0px',
      right: 'auto',
      bottom: 'auto',
      maxHeight: maxHeight + 'px',
      overflowY: 'auto'
    });

    var width = tooltip.outerWidth();
    var height = Math.min(tooltip.outerHeight(), maxHeight);
    var left = targetRect.left;
    var top = targetRect.bottom + 6;

    if(left + width > window.innerWidth - viewportPadding) {
      left = window.innerWidth - width - viewportPadding;
    }
    if(top + height > window.innerHeight - viewportPadding) {
      top = targetRect.top - height - 6;
    }

    left = Math.max(viewportPadding, left);
    top = Math.max(viewportPadding, Math.min(top, window.innerHeight - height - viewportPadding));

    tooltip.css({
      top: top + 'px',
      left: left + 'px',
      visibility: 'visible'
    });
  },

